logger = logging.getLogger(__name__)

COLOR_PRIMARY   = colors.HexColor("#1a1a2e")
COLOR_ACCENT    = colors.HexColor("#e94560")
COLOR_SECONDARY = colors.HexColor("#16213e")
COLOR_WHITE     = colors.white
COLOR_GRAY      = colors.HexColor("#888888")


def generate_pdf_report(attacker: Attacker, threat: Threat, events: list) -> bytes:
    buffer  = BytesIO()
    doc     = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2*cm, rightMargin=2*cm,
        topMargin=2*cm,  bottomMargin=2*cm
    )
    styles  = getSampleStyleSheet()
    story   = []

    story.append(_header(styles))
    story.append(Spacer(1, 0.5*cm))
    story.append(HRFlowable(width="100%", thickness=2, color=COLOR_ACCENT))
    story.append(Spacer(1, 0.3*cm))

    story.append(_section_title("THREAT INTELLIGENCE REPORT", styles))
    story.append(_meta_table(attacker, threat, styles))
    story.append(Spacer(1, 0.5*cm))

    story.append(_section_title("ATTACKER PROFILE", styles))
    story.append(_profile_table(attacker, threat, styles))
    story.append(Spacer(1, 0.5*cm))
    
    story.append(_section_title("MITRE ATT&CK TECHNIQUES", styles))
    story.append(_mitre_table(threat, styles))
    story.append(Spacer(1, 0.5*cm))

    story.append(_section_title("EVENT TIMELINE", styles))
    story.append(_timeline_table(events[:50], styles))
    story.append(Spacer(1, 0.5*cm))

    story.append(_section_title("COUNTERMEASURES APPLIED", styles))
    story.append(_countermeasure_table(attacker, styles))
    story.append(Spacer(1, 0.5*cm))

    if threat and threat.recommendations:
        story.append(_section_title("RECOMMENDATIONS", styles))
        for i, rec in enumerate(threat.recommendations, 1):
            story.append(Paragraph(f"{i}. {rec}", styles["Normal"]))
        story.append(Spacer(1, 0.3*cm))

    if threat and threat.summary:
        story.append(_section_title("ANALYST SUMMARY", styles))
        story.append(Paragraph(threat.summary, styles["Normal"]))

    story.append(Spacer(1, 1*cm))
    story.append(HRFlowable(width="100%", thickness=1, color=COLOR_GRAY))
    story.append(Paragraph(
        f"Generated by RAJAWALI Cyber Defense System | {now_wib().strftime('%Y-%m-%d %H:%M WIB')}",
        ParagraphStyle("footer", fontSize=8, textColor=COLOR_GRAY, alignment=1)
    ))

    doc.build(story)
    return buffer.getvalue()


def generate_json_report(attacker: Attacker, threat: Threat, events: list) -> dict:
    return {
        "report_id":    f"RAJAWALI-{now_wib().strftime('%Y%m%d')}-{str(attacker.id)[:8].upper()}",
        "generated_at": now_wib().isoformat(),
        "system":       "RAJAWALI v1.0.0",
        "attacker": {
            "id":               str(attacker.id),
            "ip_address":       attacker.ip_address,
            "country":          attacker.country_name,
            "isp":              attacker.isp,
            "threat_score":     attacker.threat_score,
            "status":           str(attacker.status),
            "tools_detected":   attacker.tools_detected or [],
            "mitre_ttps":       attacker.mitre_ttps or [],
            "first_seen":       attacker.first_seen.isoformat() if attacker.first_seen else None,
            "last_seen":        attacker.last_seen.isoformat() if attacker.last_seen else None,
            "total_events":     attacker.total_events,
            "ssh_attempts":     attacker.ssh_attempts,
            "is_blocked":       bool(attacker.is_blocked),
        },
        "threat": {
            "level":            str(threat.threat_level) if threat else None,
            "category":         str(threat.threat_category) if threat else None,
            "is_human":         bool(threat.is_human) if threat else None,
            "timing_pattern":   threat.timing_pattern if threat else None,
            "mitre_tactics":    threat.mitre_tactics if threat else [],
            "mitre_techniques": threat.mitre_techniques if threat else [],
            "summary":          threat.summary if threat else None,
            "recommendations":  threat.recommendations if threat else [],
        },
        "events": [
            {
                "timestamp":    e.timestamp.isoformat() if e.timestamp else None,
                "type":         str(e.event_type),
                "severity":     str(e.severity),
                "mitre":        e.mitre_technique,
                "tool":         e.tool_detected,
                "port":         e.dst_port,
            }
            for e in events[:50]
        ]
    }

def _header(styles):
    return Paragraph(
        "<b>RAJAWALI</b> — Reconnaissance Awareness & Judgment for Active Warfare Intelligence",
        ParagraphStyle("header", fontSize=14, textColor=COLOR_PRIMARY, spaceAfter=4)
    )

def _section_title(title: str, styles):
    return Paragraph(
        f"<b>{title}</b>",
        ParagraphStyle("section", fontSize=11, textColor=COLOR_ACCENT, spaceBefore=8, spaceAfter=4)
    )

def _meta_table(attacker, threat, styles):
    now = now_wib().strftime("%Y-%m-%d %H:%M WIB")
    report_id = f"RAJAWALI-{now_wib().strftime('%Y%m%d')}-{str(attacker.id)[:8].upper()}"
    data = [
        ["Report ID",   report_id,  "Generated",    now],
        ["Target IP",   attacker.ip_address, "Threat Level", str(threat.threat_level if threat else "N/A").upper()],
    ]
    return _make_table(data)

def _profile_table(attacker, threat, styles):
    data = [
        ["IP Address",      attacker.ip_address,
         "Threat Score",    f"{attacker.threat_score:.1f}/100"],
        ["Country",         attacker.country_name or "Unknown",
         "Actor Type",      "Human" if (threat and threat.is_human) else "Bot"],
        ["ISP",             attacker.isp or "Unknown",
         "Timing Pattern",  threat.timing_pattern if threat else "N/A"],
        ["Tools Detected",  ", ".join(attacker.tools_detected or []) or "None",
         "Known Malicious", "YES" if attacker.is_known_malicious else "NO"],
        ["SSH Attempts",    str(attacker.ssh_attempts),
         "HTTP Attempts",   str(attacker.http_attempts)],
    ]
    return _make_table(data)

def _mitre_table(threat, styles):
    if not threat or not threat.mitre_techniques:
        return Paragraph("No MITRE techniques mapped.", styles["Normal"])
    data = [["Technique ID", "Tactic"]]
    for t in threat.mitre_techniques:
        data.append([t, "—"])
    return _make_table(data, header=True)

def _timeline_table(events, styles):
    if not events:
        return Paragraph("No events recorded.", styles["Normal"])
    data = [["Timestamp", "Type", "Severity", "MITRE", "Tool"]]
    for e in events:
        data.append([
            e.timestamp.strftime("%H:%M:%S") if e.timestamp else "N/A",
            str(e.event_type).replace("_", " ").title(),
            str(e.severity).upper(),
            e.mitre_technique or "—",
            e.tool_detected or "—",
        ])
    return _make_table(data, header=True)

def _countermeasure_table(attacker, styles):
    data = [
        ["Countermeasure",  "Status"],
        ["IP Blocked",      "APPLIED" if attacker.is_blocked else "NOT APPLIED"],
        ["Tarpit",          "APPLIED" if attacker.is_tarpitted else "NOT APPLIED"],
        ["Fake Intel Fed",  "APPLIED" if attacker.fake_intel_fed else "NOT APPLIED"],
    ]
    return _make_table(data, header=True)

def _make_table(data: list, header: bool = False):
    col_count   = max(len(row) for row in data)
    col_width   = (A4[0] - 4*cm) / col_count

    style = TableStyle([
        ("FONTSIZE",        (0,0), (-1,-1), 8),
        ("GRID",            (0,0), (-1,-1), 0.5, colors.lightgrey),
        ("ROWBACKGROUNDS",  (0,0), (-1,-1), [colors.whitesmoke, colors.white]),
        ("VALIGN",          (0,0), (-1,-1), "MIDDLE"),
        ("LEFTPADDING",     (0,0), (-1,-1), 6),
        ("RIGHTPADDING",    (0,0), (-1,-1), 6),
    ])
    if header:
        style.add("BACKGROUND",     (0,0), (-1,0), COLOR_SECONDARY)
        style.add("TEXTCOLOR",      (0,0), (-1,0), COLOR_WHITE)
        style.add("FONTNAME",       (0,0), (-1,0), "Helvetica-Bold")

    return Table(data, colWidths=[col_width]*col_count, style=style)